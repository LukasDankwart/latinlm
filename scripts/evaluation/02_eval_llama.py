from transformers import logging as hf_logging
from src.models.Llama import perform_autoregressive_completion
from src.tests.llamar_metrics import analyze_sentence_by_llm, initialize_deepseek_api, distinct_n_repetition, type_token_ratio
import argparse
import os
from src.utils.utils import load_json_to_dict_list
import pandas as pd
from concurrent.futures import ThreadPoolExecutor, as_completed
import threading

def parse_args() -> argparse.Namespace:
    """ Parses roberta specific arguments"""
    parser = argparse.ArgumentParser()
    parser.add_argument("--set-checkpoint", type=str)
    parser.add_argument("--set-evaldata", type=str)
    parser.add_argument("--set-outputdir", type=str)
    parser.add_argument(f"--skip-inference", action="store_true")
    parser.add_argument(f"--skip-metrics", action="store_true")
    parser.add_argument(f"--skip-judgment", action="store_true")

    args, unknown_args = parser.parse_known_args()
    if not args.set_checkpoint:
        raise FileNotFoundError(f"[yellow]>> Invalid or no checkpoint path is specified! [/yellow]")

    path_of_model_run = args.set_checkpoint.split("/")[:-2]

    # Fallback to standard eval data file, if no other is specified
    if not args.set_evaldata:
        args.set_evaldata = "data/llama/eval/eval_data.json"
    if not args.set_outputdir:
        args.set_outputdir = os.path.join(*path_of_model_run) + "/evaluation"

    return args


def main():
    hf_logging.set_verbosity_warning()

    # 1. Step: ───── Load Arguments ─────
    args = parse_args()
    checkpoint_path = args.set_checkpoint
    eval_data_path = args.set_evaldata
    output_dir = args.set_outputdir

    # 2. Step: ───── Load evaluation data ─────
    if not os.path.exists(eval_data_path):
        raise RuntimeError(f"[ERROR] Evaluation of Llama model stopped. Given path '{eval_data_path}' is not "
                           f"a valid .jsonl for evaluation.")
    evaluation_data = load_json_to_dict_list(eval_data_path)

    # 3. Step: ───── Perform inference run over eval data ─────
    perform_inference = not args.skip_inference
    results = None
    if perform_inference:
        tokenizer_args = {
            "tokenizer_path": "tokenizer/bpe_tokenizer.json",
            "bos_token": "<s>",
            "eos_token": "</s>",
            "unk_token": "<unk>",
            "pad_token": "<pad>"
        }
        print(f"-- [INFO] Calling inference run with tokenizer from {tokenizer_args['tokenizer_path']}")
        # Function calls autoregressive completion for original subsentences
        results = perform_autoregressive_completion(
            checkpoint_path=checkpoint_path,
            tokenizer_args=tokenizer_args,
            inputs=evaluation_data
        )
        print(f"[yellow] -- [INFO] Model was loaded from '{checkpoint_path}' [/yellow]")

        # 4. Step: ───── Store results to specified output dir ─────
        df = pd.DataFrame(results)
        output_path = os.path.join(output_dir, "autoregressive_results.csv")
        df.to_csv(output_path)
        print(f"[yellow] -- [INFO] Successfully stored inference results to '{output_path}' [/yellow]")
    else:
        print(f"[yellow] -- [INFO]>> Skipping Llamar inference.")


    # 5. Step: ───── Compute traditional metrics ─────
    if not args.skip_metrics:
        if results is not None:
            print(f"[yellow] -- [INFO] Start computing traditional metrics on generated sequences... [/yellow]")
            for (idx, res) in enumerate(results):
                metrics = {
                    "distinct-1": -1.0,
                    "distinct-2": -1.0,
                    "distinct-3": -1.0,
                    "ttr": -1.0
                }

                # First check if the results represents a real generated sequence by Llama or just original text
                cutoff_idx = int(res.get("cutoff_idx", "-1"))
                # -1 indicates the sequence was not cutted off, so Llama has not generated on this input sequence
                if cutoff_idx == -1:
                    # If the text is not generated by Llama, the metrics are not measured
                    res.update(metrics)
                    continue

                # In this case, we compute the metrics on the generated text by llama
                llama_text = res.get("generated_text", None)
                if llama_text is None:
                    res.update(metrics)
                    continue

                # 5.1: Compute distinct-n-gram for n=1,2,3
                for n in range(1, 4):
                    distinct_n = distinct_n_repetition(llama_text, n_gram=n)
                    metrics[f"distinct-{n}"] = distinct_n

                # 5.2: Compute ttr
                text_ttr = type_token_ratio(llama_text)
                metrics["ttr"] = text_ttr

                # Finally store all metric results to the result dictionary
                res.update(metrics)

                if idx % 10 == 0:
                    print(
                        f"[yellow] -- [INFO] Metrics computed for {(idx / len(results)) * 100:.2f}% of evaluation data...")
        else:
            print(f"[WARN] There is no 'results' data to compute traditional metrics on!")

    # 6. Step: ───── Call LLM-as-a-Judge Procedure ─────
    perform_llm_judgment = not args.skip_judgment
    if perform_llm_judgment:
        if results is None:
            # Load pre runned inference results
            autoregressive_results_path = os.path.join(output_dir, "autoregressive_results.csv")
            if not os.path.exists(autoregressive_results_path):
                raise RuntimeError(
                    f"[ERROR] For LLM judgement, file at: '{autoregressive_results_path}' is required (run eval without --skip-inference arg)")
            results = pd.read_csv(autoregressive_results_path).to_dict(orient='records')

        deepseek_client = initialize_deepseek_api()
        print(f"[yellow] -- [INFO] Starting LLM judgment by Deepseek ...[/yellow]")

        # Determine new path in order to not overwrite previous runs
        base_name = os.path.join(output_dir, "judgement_results_incremental")
        judged_results_path = f"{base_name}.csv"
        eval_num = 0
        while os.path.exists(judged_results_path):
            judged_results_path = f"{base_name}_{eval_num}.csv"
            eval_num += 1

        csv_lock = threading.Lock()

        def process_single_sample(res) -> bool:
            """ Function for single thread"""
            generated_text = res.get("generated_text", None)
            if generated_text is not None:
                judge_results = analyze_sentence_by_llm(client=deepseek_client, latin_sample=generated_text, retries=3)
                res.update(judge_results)
            with csv_lock:
                write_header = not os.path.exists(judged_results_path)
                pd.DataFrame([res]).to_csv(judged_results_path, mode='a', header=write_header, index=False)
            return True

        if not results:
            print(f"[WARN] There is no 'results' data for LLM-as-a-judge procedure!")
        else:
            max_parallel_requests = 10
            with ThreadPoolExecutor(max_workers=max_parallel_requests) as executor:
                futures = [executor.submit(process_single_sample, res) for res in results]
                for idx, future in enumerate(as_completed(futures), 1):
                    if idx % 10 == 0:
                        print(
                            f"[yellow] -- [INFO] Judgement completed for {((idx / len(results)) * 100):.2f}% ...[/yellow]")
    else:
        print(f"[yellow] -- [INFO]>> Skipping judgment by Deepseek.[/yellow]")

    # 6. Step: ───── Storing complete evaluation results to csv ─────
    base_eval_path = os.path.join(output_dir, "evaluation_results")
    evaluation_result_path = f"{base_eval_path}.csv"
    eval_num = 0
    # Check if previous evaluation results exist; adjust path in order to not overwrite previous results
    while os.path.exists(evaluation_result_path):
        evaluation_result_path = f"{base_eval_path}_{eval_num}.csv"
        eval_num += 1
    df = pd.DataFrame(results)
    df.to_csv(evaluation_result_path)


if __name__ == "__main__":
    main()




